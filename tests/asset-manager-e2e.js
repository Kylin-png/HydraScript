// Asset-manager end-to-end test (Stage 2) — Playwright + local Chromium.
//
// Drives the real editor UI: upload image frames, check the library panel,
// the 8 MB refusal, the 1024 px downscale, sprite image picking, animation
// setup with frame reorder, the Play Animation block listing the animation,
// the animation playing in the game preview, save/reload persistence, and
// the exported HTML embedding the uploaded assets.
//
// Usage: node tests/asset-manager-e2e.js
// Exit 0 = all checks passed. Skips (exit 0) when Chromium is unavailable.
// Fixtures live in /tmp/asset-e2e/fixtures (generated by that folder's
// gen-pngs.js); screenshots land in screenshots/asset-manager-e2e/.

const { spawn } = require('child_process');
const path = require('path');
const fs = require('fs');

const HYDRA_DIR = path.join(__dirname, '..', 'hydra');
const REPO = path.join(__dirname, '..');
const PORT = 8125;
const FIXTURES = '/tmp/asset-e2e/fixtures';
const SHOTS = path.join(REPO, 'screenshots', 'asset-manager-e2e');
const CHROME_PATH = path.join(
  process.env.HOME || '/home/hatch',
  '.cache/ms-playwright/chromium-1248/chrome-linux64/chrome'
);

let failures = 0;
function check(name, cond, detail) {
  if (cond) { console.log(`ok - ${name}`); }
  else { failures++; console.log(`NOT OK - ${name}${detail ? ' :: ' + detail : ''}`); }
}

async function main() {
  const { chromium } = require('playwright-core');
  if (!fs.existsSync(CHROME_PATH)) {
    console.log('SKIPPED - chromium not available at ' + CHROME_PATH);
    process.exit(0);
  }
  for (const f of ['frame1.png', 'frame2.png', 'frame3.png', 'big.png', 'huge.png']) {
    if (!fs.existsSync(path.join(FIXTURES, f))) {
      console.log(`SKIPPED - missing fixture ${f} (run /tmp/asset-e2e/gen-pngs.js)`);
      process.exit(0);
    }
  }
  fs.mkdirSync(SHOTS, { recursive: true });

  // stdio 'ignore': see browser-smoke.js — the server logs every request
  // to stderr, and with piped stdio nobody reads it, so the 64KB pipe
  // fills after ~1100 requests and the server blocks mid-response forever.
  const server = spawn('python3', ['-m', 'http.server', String(PORT)], { cwd: HYDRA_DIR, stdio: 'ignore' });
  await new Promise(r => setTimeout(r, 1200));

  const browser = await chromium.launch({ executablePath: CHROME_PATH });
  const context = await browser.newContext({ viewport: { width: 1400, height: 900 }, acceptDownloads: true });
  const page = await context.newPage();
  const consoleErrors = [];
  const pageErrors = [];
  const dialogs = [];
  page.on('console', m => { if (m.type() === 'error') consoleErrors.push(m.text()); });
  page.on('pageerror', e => pageErrors.push(String(e && e.message || e)));
  page.on('dialog', async d => { dialogs.push(d.message()); await d.accept(); });

  const assetIdsByName = async () => page.evaluate(() => {
    const out = {};
    for (const [id, rec] of Object.entries(window.assetLibrary || {})) out[rec.name] = { id, ...rec };
    return out;
  });

  try {
    // ---- new blank project ----
    await page.goto(`http://localhost:${PORT}/home.html`, { waitUntil: 'domcontentloaded' });
    await page.click('#new-project-btn-main');
    await page.fill('#project-name-input', 'Asset Manager E2E');
    await page.click('.template-card[data-template="blank"]');
    await Promise.all([
      page.waitForURL(/index\.html/, { timeout: 15000 }),
      page.click('#create-project-btn')
    ]);
    await page.waitForFunction(
      () => document.getElementById('app-loading-screen')?.classList.contains('hidden'),
      null, { timeout: 15000 });
    check('editor opens on blank project', /index\.html/.test(page.url()), page.url());

    // ---- Assets tab: upload 3 frames ----
    await page.click('.inspector-tab[data-inspector-tab="assets"]');
    await page.setInputFiles('#asset-upload-file', [
      path.join(FIXTURES, 'frame1.png'),
      path.join(FIXTURES, 'frame2.png'),
      path.join(FIXTURES, 'frame3.png'),
    ]);
    await page.waitForFunction(
      () => document.querySelectorAll('#asset-list .asset-row').length === 3,
      null, { timeout: 10000 });
    const rowNames = await page.locator('#asset-list .asset-name').allTextContents();
    check('library lists the 3 uploaded frames',
      ['frame1.png', 'frame2.png', 'frame3.png'].every(n => rowNames.includes(n)),
      rowNames.join(', '));
    await page.screenshot({ path: path.join(SHOTS, '01-asset-library.png') });

    // ---- oversized image still downscales to 1024 px ----
    await page.setInputFiles('#asset-upload-file', [path.join(FIXTURES, 'big.png')]);
    await page.waitForFunction(
      () => document.querySelectorAll('#asset-list .asset-row').length === 4,
      null, { timeout: 10000 });
    const big = (await assetIdsByName())['big.png'];
    check('2048 px image downscaled to 1024 px on upload',
      big && big.width === 1024 && big.height === 256,
      big ? `${big.width}x${big.height}` : 'big.png missing');

    // ---- file over 8 MB is refused with a plain message ----
    dialogs.length = 0;
    await page.setInputFiles('#asset-upload-file', [path.join(FIXTURES, 'huge.png')]);
    await page.waitForTimeout(800);
    const refused = dialogs.join('\n');
    check('over-8 MB file refused with a clear message',
      /huge\.png/.test(refused) && /8\.00 MB/.test(refused), refused.slice(0, 200));
    check('refused file never entered the library',
      (await page.locator('#asset-list .asset-row').count()) === 4);

    // ---- create a sprite, pick an uploaded image as its appearance ----
    await page.click('.inspector-tab[data-inspector-tab="create"]');
    await page.selectOption('#new-object-kind', 'sprite');
    await page.click('#add-object-btn');
    await page.waitForSelector('.game-object.selected', { timeout: 5000 });
    await page.click('.inspector-tab[data-inspector-tab="inspect"]');
    await page.waitForSelector('.animation-editor', { timeout: 5000 });
    // A fresh sprite starts unnamed, and blocks target objects by name:
    // the Animations section says so and points at the Name field.
    check('animations section prompts for a name on an unnamed sprite',
      await page.locator('.animation-name-prompt').count() === 1);
    await page.locator('#object-properties input[placeholder^="e.g. player"]').fill('Hero');
    // The name applies on input; the panel re-renders on the next selection.
    await page.locator('.game-object.selected').click();
    await page.waitForTimeout(300);
    check('naming the sprite clears the prompt',
      await page.locator('.animation-name-prompt').count() === 0);
    const lib = await assetIdsByName();
    const pick = page.locator('.upload-section select');
    check('sprite panel offers a pick-from-Assets select',
      await pick.count() === 1);
    await pick.selectOption(lib['frame1.png'].id);
    await page.waitForSelector('.upload-section .asset-preview', { timeout: 5000 });
    const previewSrc = await page.locator('.upload-section .asset-preview').getAttribute('src');
    check('picked library image becomes the sprite appearance',
      previewSrc === lib['frame1.png'].dataUrl);
    await page.screenshot({ path: path.join(SHOTS, '02-sprite-picked-image.png') });

    // ---- build the animation: 3 frames, 4 fps, loop ----
    await page.click('.animation-editor button:has-text("+ Add animation")');
    await page.waitForSelector('.animation-card', { timeout: 5000 });
    const card = page.locator('.animation-card').first();
    const frameSelect = card.locator('select').nth(1);
    for (const name of ['frame1.png', 'frame2.png', 'frame3.png']) {
      await frameSelect.selectOption(lib[name].id);
      await page.waitForTimeout(300);
    }
    const frameTitles = await page.locator('.animation-frame img').evaluateAll(
      els => els.map(e => e.title));
    check('frames land in picked order',
      JSON.stringify(frameTitles) === JSON.stringify(['frame1.png', 'frame2.png', 'frame3.png']),
      frameTitles.join(', '));
    await card.locator('input[type="number"]').first().fill('4');

    // ---- reorder: move the first frame later ----
    await page.locator('.animation-frame-move.move-right').first().click();
    await page.waitForTimeout(300);
    const reordered = await page.locator('.animation-frame img').evaluateAll(
      els => els.map(e => e.title));
    check('frame reorder moves a frame later',
      JSON.stringify(reordered) === JSON.stringify(['frame2.png', 'frame1.png', 'frame3.png']),
      reordered.join(', '));
    await page.screenshot({ path: path.join(SHOTS, '03-animation-built.png') });

    // ---- editor preview cycles the frames ----
    await card.locator('button:has-text("Preview")').first().click();
    const samples = [];
    for (let i = 0; i < 4; i++) {
      await page.waitForTimeout(300);
      samples.push(await page.locator('.animation-preview-img').getAttribute('src'));
    }
    const distinct = new Set(samples.filter(Boolean)).size;
    check('editor preview cycles through frames', distinct >= 2,
      `${distinct} distinct frames in 4 samples`);
    await page.screenshot({ path: path.join(SHOTS, '04-animation-preview.png') });
    await card.locator('button:has-text("Stop")').first().click().catch(() => {});

    // ---- play at start, then the game preview plays the animation ----
    const editor = page.locator('.animation-editor');
    await editor.locator('select').last().selectOption('Animation 1');
    await page.click('.tab[data-tab="preview-tab"]');
    await page.waitForSelector('#game-canvas', { timeout: 10000 }).catch(() => {});
    await page.waitForTimeout(1200);
    await page.screenshot({ path: path.join(SHOTS, '05-game-preview-a.png') });
    // Sample the canvas pixels directly: the sprite cycles red/green/blue
    // at 4 fps, so the dominant frame color must change across samples.
    // (Two screenshots 700 ms apart cannot prove this — 700 ms is nearly
    // one full 3-frame loop at 4 fps, so both shots can land on one frame.)
    const FRAME_RGB = [[220, 38, 38], [34, 160, 60], [37, 99, 235]];
    const dominantFrame = () => page.evaluate((colors) => {
      const c = document.getElementById('game-canvas');
      if (!c) return -1;
      const data = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
      const counts = [0, 0, 0];
      for (let i = 0; i < data.length; i += 16) {
        for (let k = 0; k < 3; k++) {
          if (data[i] === colors[k][0] && data[i + 1] === colors[k][1] && data[i + 2] === colors[k][2]) { counts[k]++; break; }
        }
      }
      const max = Math.max(...counts);
      return max > 0 ? counts.indexOf(max) : -1;
    }, FRAME_RGB);
    const seenFrames = new Set();
    for (let i = 0; i < 12; i++) {
      seenFrames.add(await dominantFrame());
      await page.waitForTimeout(150);
    }
    await page.screenshot({ path: path.join(SHOTS, '06-game-preview-b.png') });
    const played = [...seenFrames].filter(f => f >= 0);
    check('game preview cycles the animation frames (pixel sampling)',
      new Set(played).size >= 2, `dominant frames seen: ${played.join(', ')}`);

    // ---- Play Animation block lists the animation by name ----
    await page.click('.tab[data-tab="script-tab"]');
    await page.waitForSelector('#grid', { timeout: 10000 });
    check('Play Animation block is in the palette',
      await page.locator('.block-selector .block-option[data-block-type="play-animation"]').count() === 1);
    const playBefore = await page.locator('#grid [data-block-type="play-animation"]').count();
    await page.click('.block-selector .block-option[data-block-type="play-animation"]');
    await page.locator('#grid > *:not([data-block-type])').first().click();
    await page.waitForFunction(
      (n) => document.querySelectorAll('#grid [data-block-type="play-animation"]').length > n,
      playBefore, { timeout: 5000 }).catch(() => {});
    const placed = await page.locator('#grid [data-block-type="play-animation"]').count();
    check('Play Animation block places on the grid', placed === playBefore + 1, `placed=${placed}`);
    await page.locator('#grid [data-block-type="play-animation"]').first().click();
    // Point the block at the sprite, then the Animation picker lists its animation.
    const objSelect = page.locator('#properties-panel select, #properties-content select').first();
    const objOptions = await objSelect.locator('option').evaluateAll(
      els => els.map(e => ({ v: e.value, t: e.textContent.trim() })).filter(o => o.v));
    check('block Object picker lists the named sprite', objOptions.some(o => o.v === 'Hero'),
      JSON.stringify(objOptions));
    if (objOptions.length) {
      await objSelect.selectOption(objOptions[0].v);
      await page.waitForTimeout(300);
      // The panel holds Object, Target-matching, and Animation selects in
      // that order; find the one offering the animation by name.
      const allSelectOptions = await page.locator('#properties-content select').evaluateAll(
        els => els.map(s => [...s.options].map(o => o.value)));
      check('block Animation picker lists the manager-built animation',
        allSelectOptions.some(opts => opts.includes('Animation 1')),
        JSON.stringify(allSelectOptions));
    }
    await page.screenshot({ path: path.join(SHOTS, '07-play-animation-block.png') });

    // ---- save, reload, and the assets + animation survive ----
    await page.click('#save-project-btn');
    await page.waitForTimeout(600);
    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForFunction(
      () => document.getElementById('app-loading-screen')?.classList.contains('hidden'),
      null, { timeout: 15000 });
    const saved = await page.evaluate(() => {
      const all = JSON.parse(localStorage.getItem('hydraProjects') || '{}');
      const projects = Object.values(all);
      const current = projects.find(p => p && p.name === 'Asset Manager E2E') || projects[0];
      if (!current) return null;
      const sprite = (current.scenes || []).flatMap(s => s.objects || [])
        .find(o => o && o.animations && o.animations.length);
      return {
        assetCount: Object.keys(current.assets || {}).length,
        assetNames: Object.values(current.assets || {}).map(a => a.name),
        animFrames: sprite ? sprite.animations[0].frames.length : 0,
        animName: sprite ? sprite.animations[0].name : '',
        startAnim: sprite ? sprite.startAnimation : '',
        spriteAsset: sprite ? !!sprite.assetId : false,
      };
    });
    check('save/reload keeps all 4 assets',
      saved && saved.assetCount === 4, saved ? `${saved.assetCount}: ${saved.assetNames.join(', ')}` : 'no saved project');
    check('save/reload keeps the 3-frame animation and play-at-start',
      saved && saved.animFrames === 3 && saved.animName === 'Animation 1' && saved.startAnim === 'Animation 1',
      JSON.stringify(saved));
    check('save/reload keeps the sprite image', saved && saved.spriteAsset === true);

    // ---- exported standalone HTML embeds the uploaded assets ----
    const exported = await page.evaluate(() => {
      const all = JSON.parse(localStorage.getItem('hydraProjects') || '{}');
      const current = Object.values(all).find(p => p && p.name === 'Asset Manager E2E');
      if (!current || !window.HydraPlayer) return '';
      return window.HydraPlayer.buildPlayableHtml(current) || '';
    });
    check('exported HTML embeds the uploaded frames',
      exported.includes('frame1.png') && exported.includes('frame2.png') &&
      exported.includes('data:image/png;base64'),
      `export length ${exported.length}`);
  } finally {
    // Font Awesome comes from a CDN the sandbox cannot reach (browser-smoke
    // documents the same); resource-load failures are environmental, not
    // engine errors, so they are reported but do not fail the run.
    const resourceNoise = /Failed to load resource|ERR_TUNNEL_CONNECTION_FAILED|ERR_NAME_NOT_RESOLVED|net::ERR_/;
    const realErrors = consoleErrors.filter(m => !resourceNoise.test(m));
    console.log(`console errors: ${consoleErrors.length} (${realErrors.length} real) | page errors: ${pageErrors.length}`);
    if (realErrors.length) console.log('  console: ' + realErrors.slice(0, 5).join(' | '));
    if (pageErrors.length) console.log('  page: ' + pageErrors.slice(0, 5).join(' | '));
    check('no real console errors during the whole flow', realErrors.length === 0,
      realErrors.slice(0, 3).join(' | '));
    check('no page errors during the whole flow', pageErrors.length === 0,
      pageErrors.slice(0, 3).join(' | '));
    await browser.close().catch(() => {});
    server.kill();
  }

  console.log(failures === 0 ? 'ALL ASSET-MANAGER E2E CHECKS PASSED' : `${failures} CHECK(S) FAILED`);
  process.exit(failures === 0 ? 0 : 1);
}

main().catch(e => { console.error('E2E CRASH:', e); process.exit(1); });
